"""Predict flower classes using a checkpoint produced by train.py."""
import argparse
import json
from pathlib import Path

import torch
from PIL import Image
from torchvision import transforms

from train import MEAN, STD, build_model


def load_model_from_checkpoint(checkpoint_path):
    """Rebuild the model from a safe state-dictionary checkpoint."""
    checkpoint = torch.load(checkpoint_path, map_location="cpu", weights_only=True)
    model = build_model(
        checkpoint["architecture"],
        hidden_units=checkpoint["hidden_units"],
        pretrained=False,
    )
    model.load_state_dict(checkpoint["model_state_dict"])
    model.class_to_idx = checkpoint["class_to_idx"]
    model.eval()
    return model


def process_image(image_path):
    """Apply the same image preprocessing as validation and testing."""
    transform = transforms.Compose([
        transforms.Resize(256),
        transforms.CenterCrop(224),
        transforms.ToTensor(),
        transforms.Normalize(MEAN, STD),
    ])
    with Image.open(image_path) as image:
        return transform(image.convert("RGB"))


def predict(image_path, model, device, top_k=5):
    """Return top-k probabilities and dataset class labels."""
    if not isinstance(top_k, int) or not 1 <= top_k <= len(model.class_to_idx):
        raise ValueError("top_k must be between 1 and the number of classes")
    model = model.to(device)
    model.eval()
    image = process_image(image_path).unsqueeze(0).to(device)
    with torch.inference_mode():
        log_probs = model(image)
        probs, indices = log_probs.exp().topk(top_k, dim=1)
    idx_to_class = {index: category for category, index in model.class_to_idx.items()}
    classes = [idx_to_class[index] for index in indices[0].cpu().tolist()]
    return probs[0].cpu().tolist(), classes


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("image_path", help="Path to a flower image")
    parser.add_argument("checkpoint", help="Checkpoint generated by train.py")
    parser.add_argument("--top_k", type=int, default=5)
    parser.add_argument("--category_names", default="cat_to_name.json")
    parser.add_argument("--gpu", action="store_true", help="Use CUDA if available")
    return parser.parse_args()


def main():
    args = parse_args()
    device = torch.device(
        "cuda" if args.gpu and torch.cuda.is_available() else
        "mps" if torch.backends.mps.is_available() else "cpu"
    )
    model = load_model_from_checkpoint(args.checkpoint)
    probabilities, classes = predict(args.image_path, model, device, args.top_k)
    with open(args.category_names, encoding="utf-8") as f:
        names = json.load(f)
    print(f"Image: {Path(args.image_path).name}")
    print(f"Device: {device}")
    for rank, (probability, category) in enumerate(zip(probabilities, classes), 1):
        print(f"{rank}. {names.get(str(category), str(category))}: {probability:.2%}")


if __name__ == "__main__":
    main()
